"""
Generate synthetic questions and answers for CLEVR images. Input is
a single JSON file containing ground-truth scene information for all images, and 
output is a single JSON file containing all generated questions, answers, and programs.

Questions are generated by expanding templates. Each template contains a single
program template and one or more text templates, both with the same set of typed
slots; by convention <Z> = Size, <C> = Color, <M> = Material, <S> = Shape.
We assume that the desired slot values are also provided in the input template.

Program templates may contain special nodes that expand into multiple functions
during instantiation; for example a "filter" node in a program template will
expand into a combination of "filter_size", "filter_color", "filter_material",
and "filter_shape" nodes after instantiation, and a "filter_unique" node in a
template will expand into some combination of filtering nodes followed by a
"unique" node.

In the original CLEVR code, templates are instantiated using depth-first search; 
we are looking for template
instantiations where (1) each "unique" node actually refers to a single object,
(2) constraints in the template are satisfied, and (3) the answer to the question
passes our rejection sampling heuristics. 

After our modification to the original CLEVR code, this is technically still
happening, but we force it to explore only the exact option we care about.  

To efficiently handle (1) and (2), we keep track of partial evaluations of the
program during each step of template expansion. This together with the use of
composite nodes in program templates (filter_unique, relate_filter_unique) allow
us to efficiently prune the search space and terminate early when we know that
(1) or (2) will be violated.
"""


def precompute_filter_options(scene_struct, metadata):
    # Keys are tuples (size, color, shape, material) (where some may be None)
    # and values are lists of object idxs that match the filter criterion
    attribute_map = {}

    if metadata["dataset"] == "CLEVR-v1.0":
        attr_keys = ["size", "color", "material", "shape"]
    else:
        assert False, "Unrecognized dataset"

    # Precompute masks
    # i.e., Create list of lists. Each inner list is of 4 elements. 0 or 1
    #       indicating whether we should include this attribute for filtering
    masks = []
    for i in range(2 ** len(attr_keys)):
        mask = []
        for j in range(len(attr_keys)):
            mask.append((i // (2**j)) % 2)
        masks.append(mask)

    for object_idx, obj in enumerate(scene_struct["objects"]):
        if metadata["dataset"] == "CLEVR-v1.0":
            keys = [
                tuple(obj[k] for k in attr_keys)
            ]  # list the object's size, colour, material & shape

        for mask in masks:  # for each possible subset of attributes
            for key in keys:  # for each object description
                masked_key = []
                for a, b in zip(key, mask):
                    if b == 1:
                        masked_key.append(a)
                    else:
                        masked_key.append(None)
                masked_key = tuple(
                    masked_key
                )  # Based on the mask, create masked_key by replacing some object descriptors with None
                if masked_key not in attribute_map:
                    attribute_map[masked_key] = set()
                attribute_map[masked_key].add(
                    object_idx
                )  # Record that the object matches this subset of attributes.

    scene_struct[
        "_filter_options"
    ] = attribute_map  # Record this information in the scene struct


def find_filter_options(object_idxs, scene_struct, metadata):
    # Keys are tuples (size, color, shape, material) (where some may be None)
    # and values are lists of object idxs that match the filter criterion

    if "_filter_options" not in scene_struct:
        # Create mapping from (size, color, material, shape) to the set of objects
        # in the scene graph
        # that match this description. We omit any descriptions that describe
        # zero objects.
        precompute_filter_options(scene_struct, metadata)

    # Create a map from (size, color, material, shape) to the set of objects
    # *within object_idxs* that match the description.
    attribute_map = {}
    object_idxs = set(object_idxs)
    for k, vs in scene_struct["_filter_options"].items():
        attribute_map[k] = sorted(list(object_idxs & vs))  # set intersection
    return attribute_map


def find_relate_filter_options(
    object_idx,
    scene_struct,
    metadata,
    unique=False,
    include_zero=False,
    trivial_frac=0.1,
):  # This is relate[x](obj_idx) & filter[y]
    options = {}
    if "_filter_options" not in scene_struct:
        precompute_filter_options(scene_struct, metadata)

    # NOTE: Right now this is only looking for nontrivial combinations; in some
    # cases I may want to add trivial combinations, either where the intersection
    # is empty or where the intersection is equal to the filtering output.
    # NOTE: original code considers relation as trivial if it is not
    #       required given the filter[x] calls.
    #       Although, weirdly, the original comment implies no trivial
    #       combinations, yet the code seems to go with 10% trivial. Weird.
    trivial_options = {}
    for relationship in scene_struct["relationships"]:
        related = set(scene_struct["relationships"][relationship][object_idx])
        for filters, filtered in scene_struct["_filter_options"].items():
            intersection = related & filtered
            trivial = intersection == filtered
            if unique and len(intersection) != 1:
                continue
            if not include_zero and len(intersection) == 0:
                continue
            if trivial:
                trivial_options[(relationship, filters)] = sorted(list(intersection))
            else:
                options[(relationship, filters)] = sorted(list(intersection))

    N, f = len(options), trivial_frac
    num_trivial = int(round(N * f / (1 - f)))
    trivial_options = list(trivial_options.items())
    for k, v in trivial_options[:num_trivial]:
        options[k] = v

    return options


def node_shallow_copy(node):
    new_node = {
        "type": node["type"],
        "inputs": node["inputs"],
    }
    if "side_inputs" in node:
        new_node["side_inputs"] = node["side_inputs"]
        new_node["side_input_vals"] = node["side_input_vals"]
    return new_node


def other_heuristic(text, param_vals):
    """
    Post-processing heuristic to handle the word "other"
    """
    if " other " not in text and " another " not in text:
        return text
    target_keys = {
        "<Z>",
        "<C>",
        "<M>",
        "<S>",
        "<Z2>",
        "<C2>",
        "<M2>",
        "<S2>",
    }
    if param_vals.keys() != target_keys:
        return text
    key_pairs = [
        ("<Z>", "<Z2>"),
        ("<C>", "<C2>"),
        ("<M>", "<M2>"),
        ("<S>", "<S2>"),
    ]
    remove_other = False
    for k1, k2 in key_pairs:
        v1 = param_vals.get(k1, None)
        v2 = param_vals.get(k2, None)
        if v1 != "" and v2 != "" and v1 != v2:
            print("other has got to go! %s = %s but %s = %s" % (k1, v1, k2, v2))
            remove_other = True
            break
    if remove_other:
        if " other " in text:
            text = text.replace(" other ", " ")
        if " another " in text:
            text = text.replace(" another ", " a ")
    return text


def instantiate_templates_dfs(
    scene_struct,
    template,
    metadata,
    synonyms,
    max_instances=None,
    verbose=False,
    reject_degenerate=False,
    seed: Optional[int] = None,
    value_remap: Optional[Dict[str, str]] = None,
):
    random_gen = random.Random(seed)

    param_name_to_type = {p["name"]: p["type"] for p in template["params"]}
    # We assume a modified version of the CLEVR template that also specifies value:

    initial_state = {
        "nodes": [node_shallow_copy(template["nodes"][0])],
        "vals": {},
        "input_map": {0: 0},
        "next_template_node": 1,
    }
    states = [initial_state]
    final_states = []
    while states:
        state = states.pop()

        # Check to make sure the current state is valid
        q = {"nodes": state["nodes"]}
        outputs = qeng.answer_question(q, metadata, scene_struct, all_outputs=True)
        answer = outputs[-1]
        if answer == "__INVALID__":
            raise ValueError("Provided question malformed for scene graph.")

        # Check to make sure constraints are satisfied for the current state
        skip_state = False
        for constraint in template["constraints"]:
            if constraint["type"] == "NEQ":
                p1, p2 = constraint["params"]
                v1, v2 = state["vals"].get(p1), state["vals"].get(p2)
                if v1 is not None and v2 is not None and v1 != v2:
                    if verbose:
                        print("skipping due to NEQ constraint")
                        print(constraint)
                        print(state["vals"])
                    skip_state = True
                    break
            elif (
                constraint["type"] == "NULL"
            ):  # Ensure we *aren't* filtering by the specified attribute(s)
                p = constraint["params"][0]
                p_type = param_name_to_type[p]
                v = state["vals"].get(p)
                if v is not None:
                    skip = False
                    if p_type == "Shape" and v != "thing":
                        skip = True
                    if p_type != "Shape" and v != "":
                        skip = True
                    if skip:
                        if verbose:
                            print("skipping due to NULL constraint")
                            print(constraint)
                            print(state["vals"])
                        skip_state = True
                        break
            elif (
                constraint["type"] == "OUT_NEQ"
            ):  # I *think* this ensures different sub-programs have different intermediate results.
                i, j = constraint["params"]
                i = state["input_map"].get(i, None)
                j = state["input_map"].get(j, None)
                if i is not None and j is not None and outputs[i] == outputs[j]:
                    if verbose:
                        print("skipping due to OUT_NEQ constraint")
                        print(outputs[i])
                        print(outputs[j])
                    skip_state = True
                    break
            else:
                assert False, 'Unrecognized constraint type "%s"' % constraint["type"]

        if skip_state:
            raise ValueError(
                "Question generation shouldn't skip due to bad constraints."
            )

        # We have already checked to make sure the answer is valid, so if we have
        # processed all the nodes in the template then the current state is a valid
        # question, so add it if it is not degenerate
        if state["next_template_node"] == len(template["nodes"]):
            # If the template contains a raw relate node then we need to check for
            # degeneracy at the end
            # "A question is degenerate if replacing any of its relate nodes with a scene
            #  node results in a question with the same answer."
            # NOTE: Some minimal examples are degenerate, but we account for that
            #       via balanced design. Therefore we make rejection based on
            #       this degeneracy check disableable.
            has_relate = any(n["type"] == "relate" for n in template["nodes"])
            if has_relate and reject_degenerate:
                degen = qeng.is_degenerate(
                    q, metadata, scene_struct, answer=answer, verbose=verbose
                )
                if degen:
                    print(
                        "Template contains raw relate node and is degenerate (i.e., replacing relate with scene results in same answer)"
                    )
                    raise ValueError(
                        "Template contains raw relate node and is degenerate (i.e., replacing relate with scene results in same answer)"
                    )

            state["answer"] = answer
            final_states.append(state)
            if max_instances is not None and len(final_states) == max_instances:
                break
            continue  # The DFS search has reached a leaf node, start searching the next node in the queue

        # Otherwise fetch the next node from the template
        # Make a shallow copy so cached _outputs don't leak ... this is very nasty
        next_node = template["nodes"][state["next_template_node"]]
        next_node = node_shallow_copy(next_node)

        special_nodes = {
            "filter_unique",
            "filter_count",
            "filter_exist",
            "filter",
            "relate_filter",
            "relate_filter_unique",
            "relate_filter_count",
            "relate_filter_exist",
        }
        if next_node["type"] in special_nodes:
            if next_node["type"].startswith("relate_filter"):
                unique = next_node["type"] == "relate_filter_unique"
                include_zero = (
                    next_node["type"] == "relate_filter_count"
                    or next_node["type"] == "relate_filter_exist"
                )
                filter_options = find_relate_filter_options(
                    answer,
                    scene_struct,
                    metadata,
                    unique=unique,
                    include_zero=include_zero,
                )
                # Check if target is member (direction (size, color, material, shape)); else map to [].
                assert len(next_node["side_inputs"]) == 5
                desired_filter = (
                    next_node["side_input_vals"][0],
                    tuple(next_node["side_input_vals"][ind] for ind in range(1, 5)),
                )
                if desired_filter in filter_options:
                    filter_options = {desired_filter: filter_options[desired_filter]}
                else:
                    filter_options = {desired_filter: []}
                if unique:
                    if len(filter_options[desired_filter]) != 1:
                        raise ValueError(
                            "Sub-program should isolate a unique object, yet finds several objects\n"
                            + str(scene_struct)
                            + "\n"
                            + str(state)
                        )
                if not include_zero:
                    if len(filter_options[desired_filter]) == 0:
                        raise ValueError(
                            "Sub-program returns zero objects, when it should return at least one.\n"
                            + str(scene_struct)
                            + "\n"
                            + str(state)
                        )

            else:
                filter_options = find_filter_options(answer, scene_struct, metadata)
                assert len(next_node["side_inputs"]) == 4
                # NOTE: Ordering MUST be (size, color, material, shape). The original code assumes that.
                desired_filter = tuple(
                    next_node["side_input_vals"][ind] for ind in range(4)
                )
                if desired_filter in filter_options:
                    filter_options = {desired_filter: filter_options[desired_filter]}
                else:
                    filter_options = {desired_filter: []}

                if next_node["type"] == "filter":
                    # Remove null filter
                    assert (None, None, None, None) not in filter_options
                if next_node["type"] == "filter_unique":
                    if len(filter_options[desired_filter]) != 1:
                        raise ValueError(
                            "The filter_unique node does not produce a unique object\n"
                            + str(scene_struct)
                            + "\n"
                            + str(state)
                        )

            filter_option_keys = list(filter_options.keys())
            for (
                k
            ) in (
                filter_option_keys
            ):  # Iterating over possible filter choices (for special nodes)
                new_nodes = []
                cur_next_vals = {k: v for k, v in state["vals"].items()}
                next_input = state["input_map"][next_node["inputs"][0]]
                filter_side_inputs = next_node["side_inputs"]
                if next_node["type"].startswith("relate"):
                    param_name = next_node["side_inputs"][
                        0
                    ]  # First one should be relate
                    filter_side_inputs = next_node["side_inputs"][1:]
                    param_type = param_name_to_type[param_name]
                    assert param_type == "Relation"
                    param_val = k[0]
                    k = k[1]
                    new_nodes.append(
                        {
                            "type": "relate",
                            "inputs": [next_input],
                            "side_inputs": [param_val],
                        }
                    )
                    cur_next_vals[param_name] = param_val
                    next_input = len(state["nodes"]) + len(new_nodes) - 1
                for param_name, param_val in zip(
                    filter_side_inputs, k
                ):  # Iterate over each attribute value in k, and corresponding attribute name in filter_side_inputs
                    param_type = param_name_to_type[param_name]
                    filter_type = "filter_%s" % param_type.lower()
                    if param_val is not None:
                        new_nodes.append(
                            {
                                "type": filter_type,
                                "inputs": [next_input],
                                "side_inputs": [param_val],
                            }
                        )
                        cur_next_vals[param_name] = param_val
                        next_input = len(state["nodes"]) + len(new_nodes) - 1
                    elif param_val is None:
                        if (
                            metadata["dataset"] == "CLEVR-v1.0"
                            and param_type == "Shape"
                        ):
                            param_val = "thing"
                        else:
                            param_val = ""
                        cur_next_vals[param_name] = param_val
                input_map = {k: v for k, v in state["input_map"].items()}
                extra_type = None
                if next_node["type"].endswith("unique"):
                    extra_type = "unique"
                if next_node["type"].endswith("count"):
                    extra_type = "count"
                if next_node["type"].endswith("exist"):
                    extra_type = "exist"
                if extra_type is not None:
                    new_nodes.append(
                        {
                            "type": extra_type,
                            "inputs": [
                                input_map[next_node["inputs"][0]] + len(new_nodes)
                            ],
                        }
                    )
                input_map[state["next_template_node"]] = (
                    len(state["nodes"]) + len(new_nodes) - 1
                )  # input for next node is the unholy mash we just made.
                states.append(
                    {
                        "nodes": state["nodes"] + new_nodes,
                        "vals": cur_next_vals,  # Arguments that have been set (e.g., <C> might map to "red")
                        "input_map": input_map,  # index in template -> the index for the input, in the constructed program.
                        "next_template_node": state["next_template_node"] + 1,
                    }
                )

        elif "side_inputs" in next_node:
            # If the next node has template parameters, expand them out
            # NOTE: only works for nodes with at most one side input
            assert len(next_node["side_inputs"]) == 1, "NOT IMPLEMENTED"

            # Use provided template to figure out the value for this parameter.
            param_name = next_node["side_inputs"][0]
            # param_type = param_name_to_type[param_name]
            param_vals = [
                next_node["side_input_vals"][0]
            ]  # metadata['types'][param_type][:]  # Set the 'side input' (i.e., value inside of []'s) to whatever's in the spec

            for val in param_vals:
                input_map = {k: v for k, v in state["input_map"].items()}
                input_map[state["next_template_node"]] = len(state["nodes"])
                cur_next_node = {
                    "type": next_node["type"],
                    "inputs": [input_map[idx] for idx in next_node["inputs"]],
                    "side_inputs": [val],
                }
                cur_next_vals = {k: v for k, v in state["vals"].items()}
                cur_next_vals[param_name] = val

                states.append(
                    {
                        "nodes": state["nodes"] + [cur_next_node],
                        "vals": cur_next_vals,
                        "input_map": input_map,
                        "next_template_node": state["next_template_node"] + 1,
                    }
                )
        else:
            input_map = {k: v for k, v in state["input_map"].items()}
            input_map[state["next_template_node"]] = len(state["nodes"])
            next_node = {
                "type": next_node["type"],
                "inputs": [input_map[idx] for idx in next_node["inputs"]],
            }
            states.append(
                {
                    "nodes": state["nodes"] + [next_node],
                    "vals": state["vals"],
                    "input_map": input_map,
                    "next_template_node": state["next_template_node"] + 1,
                }
            )

    # Actually instantiate the template with the solutions we've found
    text_questions, structured_questions, answers = [], [], []

    # For each "value" (e.g., <Z>, <C>, <M>, <S>, <R>, etc...) choose what
    # random substitution would be used -- this has to be done to ensure
    # consistency (i.e., that <M> will always convert rubber to matte
    # regardless of the other variables' value)
    # This random selection is done independent of values, therefore it is
    # consistent across the provided values, as we want.
    synonym_by_val = {}
    for param in template["params"]:
        synonym_by_val[param["name"]] = copy.deepcopy(synonyms)
        for word in synonym_by_val[param["name"]]:
            synonym_by_val[param["name"]][word] = random_gen.choice(
                synonym_by_val[param["name"]][word]
            )

    # If value_remap is provided, then re-map the choices as specified.
    # e.g., If value_remap = {<Z1>: <Z2>, <Z2>:<Z2>}, then we replace our
    # originally chosen value of <Z1> with our originally chosen value for <Z2>
    # This remaping is useful for doing something like "Is Z a X" to "Is X a Z"
    # without changing the random choices
    if value_remap is not None:
        ori_syn_by_val = copy.deepcopy(synonym_by_val)
        assert ori_syn_by_val.keys() == value_remap.keys()
        synonym_by_val = {}
        for param in value_remap:
            synonym_by_val[param] = ori_syn_by_val[value_remap[param]]

    for state in final_states:
        structured_questions.append(
            state["nodes"]
        )  # I believe this is what gets saved into the final .json
        answers.append(state["answer"])
        text = random_gen.choice(template["text"])
        for name, val in state[
            "vals"
        ].items():  # Note: Synonyms only applied to <Z>, <C>, <M>, or <S> (or other such slots)
            if val in synonyms:
                # val = random_gen.choice(synonyms[val])
                val = synonym_by_val[name][val]
            text = text.replace(name, val)
            text = " ".join(text.split())
        text = replace_optionals(text, r=random_gen)
        text = " ".join(text.split())
        text = other_heuristic(
            text, state["vals"]
        )  # from the CLEVR repo: "Finally, there are some special-case heuristics to replace the word "other" with "another", "a", or the empty string in some circumstances to try and minimize ambiguity."
        text_questions.append(text)

    return text_questions, structured_questions, answers


def replace_optionals(s, r: Optional[random.Random] = None):
    """
    Each substring of s that is surrounded in square brackets is treated as
    optional and is removed with probability 0.5. For example the string

    "A [aa] B [bb]"

    could become any of

    "A aa B bb"
    "A  B bb"
    "A aa B "
    "A  B "

    with probability 1/4.
    """
    if r is None:
        r = random.Random()

    pat = re.compile(r"\[([^\[]*)\]")

    while True:
        match = re.search(pat, s)
        if not match:
            break
        i0 = match.start()
        i1 = match.end()
        if r.random() > 0.5:
            s = s[:i0] + match.groups()[0] + s[i1:]
        else:
            s = s[:i0] + s[i1:]
    return s


# Modified version of main() for our purposes.
def generate_questions(
    scene_graphs,
    template,
    q_fam_idx: int = -1,
    template_name: str = "",
    seed: Optional[int] = None,
    value_remap: Optional[Dict[str, str]] = None,
):
    """
    Note: for each question, image_filename, image_index, image, and split are set
          to None instead of the filename, index, the head of the image filename,
          and the dataset split respectively.

    :param scene_graphs:
    :param template:
    :param q_fam_idx:
    :param template_name:
    :param seed:
    :value_remap: Optionally, re-map the values chosen for the variables.
    If value_remap is provided, then re-map the choices as specified.
    e.g., If value_remap = {<Z1>: <Z2>, <Z2>:<Z2>}, then we replace our
    originally chosen value of <Z1> with our originally chosen value for <Z2>
    This remaping is useful for doing something like "Is Z a X" to "Is X a Z"
    without changing the random choices
    :return:
    """
    with open("metadata.json", "r") as f:
        metadata = json.load(f)
        dataset = metadata["dataset"]
        if dataset != "CLEVR-v1.0":
            raise ValueError('Unrecognized dataset "%s"' % dataset)

    functions_by_name = {}
    for f in metadata["functions"]:
        functions_by_name[f["name"]] = f
    metadata["_functions_by_name"] = functions_by_name

    # Instead of loading template from disk, use the user-provided template.
    # Key is (filename, file_idx)
    templates = {}
    templates[("dummy", 0)] = template

    # Read file containing input scenes
    all_scenes = scene_graphs
    # scene_info = scene_data['info']

    # Read synonyms file
    with open("synonyms.json", "r") as f:
        synonyms = json.load(f)

    questions = []
    for i, scene in enumerate(all_scenes):
        scene_struct = scene
        # print('starting image %s (%d / %d)'% (scene_fn, i + 1, len(all_scenes)))

        (
            ts,
            qs,
            ans,
        ) = instantiate_templates_dfs(  # This call creates strings & scene graphs, using a DFS search; ts is string, qs is program
            scene_struct,
            template,
            metadata,
            synonyms,
            max_instances=1,  # we're going to specify the needed details, so only one possible program.
            verbose=False,
            seed=seed,
            value_remap=value_remap,
        )

        # image_index = int(os.path.splitext(scene_fn)[0].split('_')[-1])
        for t, q, a in zip(ts, qs, ans):
            questions.append(
                {
                    "split": None,  # scene_info['split'],
                    "image_filename": None,  # scene_fn,
                    "image_index": None,  # image_index,
                    "image": None,  # os.path.splitext(scene_fn)[0],
                    "question": t,
                    "program": q,
                    "answer": a,
                    "template_filename": template_name,
                    "question_family_index": q_fam_idx,
                    "question_index": len(questions),
                }
            )
        assert len(ts) > 0  # Check we have at least one generated question here.

    # Change "side_inputs" to "value_inputs" in all functions of all functional
    # programs. My original name for these was "side_inputs" but I decided to
    # change the name to "value_inputs" for the public CLEVR release. I should
    # probably go through all question generation code and templates and rename,
    # but that could be tricky and take a while, so instead I'll just do it here.
    # To further complicate things, originally functions without value inputs did
    # not have a "side_inputs" field at all, and I'm pretty sure this fact is used
    # in some of the code above; however in the public CLEVR release all functions
    # have a "value_inputs" field, and it's an empty list for functions that take
    # no value inputs. Again this should probably be refactored, but the quick and
    # dirty solution is to keep the code above as-is, but here make "value_inputs"
    # an empty list for those functions that do not have "side_inputs". Gross.
    for q in questions:
        for f in q["program"]:
            if "side_inputs" in f:
                f["value_inputs"] = f["side_inputs"]
                del f["side_inputs"]
            else:
                f["value_inputs"] = []

            # Ugly hackery due to CLEVR code & dataset being from different times
            # https://github.com/facebookresearch/clevr-dataset-gen/issues/14
            # We need to replace "type" key with "function" key for each program node
            f["function"] = f["type"]
            f.pop("type")

        # Undocumented hackery, but looks like answer types are borked too.
        if isinstance(q["answer"], bool):
            q["answer"] = "yes" if q["answer"] else "no"
        elif isinstance(q["answer"], int):
            assert 0 <= q["answer"] <= 10
            q["answer"] = str(q["answer"])
        else:
            assert isinstance(q["answer"], str)

            # We also get bonus _output keys, but those are actually maybe useful
            # so I'm keeping 'em.

    # return {'info': scene_info, 'questions': questions}
    return questions


